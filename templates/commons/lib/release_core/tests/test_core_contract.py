# ── The shrink-only baseline ──────────────────────────────────────────────────


def test_baseline_grandfathers_listed_jobs_and_flags_stale_entries(tmp_path):
    root = str(tmp_path)
    _write_wf(root, VIOLATING_WF)
    violations = contract.lint_repo(root, MANIFEST)
    baseline = [
        {"file": ".github/workflows/wf.yml", "job": "e2e", "reason": "known"},
        {"file": ".github/workflows/gone.yml", "job": "old", "reason": "drained"},
    ]
    failing, grandfathered, stale = contract.apply_baseline(violations, baseline)
    assert failing == []
    assert len(grandfathered) == 1
    assert [e["job"] for e in stale] == ["old"]  # the ratchet: must be deleted


def test_lint_verb_fails_on_new_violation_and_stale_entry(synthetic_repo, capsys):
    assert contract_verb.main(["dump", "--root", synthetic_repo]) == 0
    _write_wf(synthetic_repo, VIOLATING_WF)
    assert contract_verb.main(["lint", "--root", synthetic_repo]) == 1
    err = capsys.readouterr().err
    assert ".github/workflows/wf.yml -> e2e -> Run E2E tests" in err

    # Baseline the job → lint passes; then fix the job → the stale entry fails.
    Path(synthetic_repo, contract.BASELINE_RELPATH).write_text(
        'known_stale_jobs:\n  - {file: ".github/workflows/wf.yml", job: "e2e", reason: "x"}\n'
    )
    assert contract_verb.main(["lint", "--root", synthetic_repo]) == 0
    _write_wf(synthetic_repo, COMPLIANT_WF)
    assert contract_verb.main(["lint", "--root", synthetic_repo]) == 1
    assert "STALE baseline entry" in capsys.readouterr().err


