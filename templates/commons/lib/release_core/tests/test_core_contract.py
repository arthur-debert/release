def _has_executable_bit(path: str) -> bool:
    return bool(os.stat(path).st_mode & stat.S_IXUSR)


def test_gate_wrappers_exist_and_are_executable():
    wrappers = (
        "bin-internal/check-consumer-contract.sh",
        "bin-internal/lint-consumer-contract.sh",
    )
    for rel in wrappers:
        full = os.path.join(REPO_ROOT, rel)
        assert os.path.isfile(full), rel
        assert _has_executable_bit(full), rel
