# ── Synthetic: the assumption lint ────────────────────────────────────────────

MANIFEST = {
    "managed_path_prefixes": [".release/", "bin/check", "lib/release_core/"],
    "untracked_mirrors": ["app-bin/smoke-hook.sh", ".editorconfig"],
}

VIOLATING_WF = """\
name: e2e
on: [push]
jobs:
  e2e:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6
      - name: Run E2E tests
        run: bin/check-e2e
"""

COMPLIANT_WF = """\
name: e2e
on: [push]
jobs:
  e2e:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6
      - name: Arm the gate toolset
        uses: arthur-debert/release/.github/actions/arm-gate@v2
      - name: Run E2E tests
        run: bin/check-e2e
"""


def _write_wf(root: str, text: str, name: str = "wf.yml") -> None:
    wf_dir = Path(root, ".github", "workflows")
    wf_dir.mkdir(parents=True, exist_ok=True)
    (wf_dir / name).write_text(text)


def test_lint_detects_the_579_shape(tmp_path):
    """A job referencing bin/check-e2e with no materialize — the exact latent
    assumption #579 fixed — must FAIL."""
    root = str(tmp_path)
    _write_wf(root, VIOLATING_WF)
    violations = contract.lint_repo(root, MANIFEST)
    assert len(violations) == 1
    v = violations[0]
    assert (v.file, v.job, v.step) == (".github/workflows/wf.yml", "e2e", "Run E2E tests")
    assert v.matched == "bin/check-e2e"


def test_lint_passes_with_arm_gate_before_the_reference(tmp_path):
    root = str(tmp_path)
    _write_wf(root, COMPLIANT_WF)
    assert contract.lint_repo(root, MANIFEST) == []


def test_lint_requires_materialize_BEFORE_the_reference(tmp_path):
    """arm-gate AFTER the referencing step does not absolve it — order matters."""
    root = str(tmp_path)
