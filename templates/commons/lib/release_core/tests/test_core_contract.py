# ── Real tree: manifest generation ────────────────────────────────────────────


def test_manifest_is_deterministic():
    assert contract.manifest_text(REPO_ROOT) == contract.manifest_text(REPO_ROOT)


def test_manifest_contains_the_contract_anchors():
    data = contract.build_manifest(REPO_ROOT)
    # The bootstrap quartet, verbatim from sync.py (sorted).
    assert data["tracked_real_files"]["bootstrap"] == sorted(sync.BOOTSTRAP_REAL_FILES)
    # The gate-internal set, verbatim from sync.py (sorted).
    assert data["gate_internal"] == sorted(sync.GATE_INTERNAL_FILES)
    # The .github/workflows real-copy rule produces the shipped workflow copy.
    assert ".github/workflows/copilot-review.yml" in data["tracked_real_files"]["workflow_copies"]
    # The ephemeral build dir.
    assert data["gitignored"] == [".release/"]
    # The #579 family is mirror dests (untracked post-WS7), never tracked files.
    mirrors = data["untracked_mirrors"]
    assert "bin/check" in mirrors
    assert "bin/check-e2e" in mirrors
    # The distributed PR-loop skill rides the mirror list.
    assert ".claude/skills/gh-pr-review-loop/SKILL.md" in mirrors
    # Managed-path prefixes are the lint's spine.
    assert data["managed_path_prefixes"] == [".release/", "bin/check", "lib/release_core/"]
    # Tombstones come from the retired sets, not a re-statement.
    assert data["tombstones"]["blob"] == sorted(sync.RETIRED_BLOB_FILES)
    assert data["tombstones"]["marker"] == sorted(sync.RETIRED_MARKER_FILES)
    assert data["tombstones"]["fingerprint"] == sorted(sync.RETIRED_FINGERPRINT_FILES)


def test_manifest_never_lists_release_internal_or_skipped_sources():
    data = contract.build_manifest(REPO_ROOT)
    listed = (
        data["tracked_real_files"]["bootstrap"]
        + data["tracked_real_files"]["workflow_copies"]
        + data["untracked_mirrors"]
    )
    for dest in listed:
        assert not sync.is_release_internal(dest), dest
        assert not dest.startswith("lib/release_core/"), dest
    # The lefthook fragments / kind manifests are sync inputs, never dests.
    assert not any(d.endswith("lefthook.fragment.yaml") for d in listed)
    assert not any(d == "manifest.yaml" for d in listed)


def test_committed_manifest_is_current():
    """The gate's freshness rule, asserted in pytest too: a PR that changes the
    contract regenerates docs/references/consumer-contract.yaml in the SAME PR."""
    committed = Path(REPO_ROOT, contract.MANIFEST_RELPATH).read_text(encoding="utf-8")
    assert committed == contract.manifest_text(REPO_ROOT), (
        "consumer-contract.yaml drifted — run: release-core admin contract dump"
    )


def test_manifest_has_no_volatile_provenance():
    text = contract.manifest_text(REPO_ROOT)
    # Byte-stability contract: no timestamps, no commit SHAs — schema field only.
    assert "contract_schema: 1" in text
    for needle in ("generated_at", "timestamp", "sha:", "Generated by release from"):
        assert needle not in text, needle


# ── Real tree: the assumption lint passes today (post-#579) ──────────────────


def test_lint_passes_on_todays_tree_with_zero_baseline():
    """Post-#588 the baseline is drained: the sweep itself is clean, no
    grandfathered jobs. A new violation OR a re-grown baseline fails here."""
    manifest = contract.build_manifest(REPO_ROOT)
    violations = contract.lint_repo(REPO_ROOT, manifest)
    assert violations == [], violations
    # The baseline FILE was deleted with the last entry (#588) — a missing
    # file is an empty baseline, and the ratchet only shrinks.
    assert not Path(REPO_ROOT, contract.BASELINE_RELPATH).exists(), (
        "the consumer-contract lint baseline was drained to zero in release#588 "
        "— do not re-create it; normalize the workflow instead"
    )
    assert contract.load_baseline(REPO_ROOT) == []


